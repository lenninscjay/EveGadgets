#!/usr/bin/env python3
"""Regenerate the PI-only MySQL seed from a fixed Fuzzwork SDE conversion.
No non-standard Python packages required. Does not touch a running database.
"""
import csv
import hashlib
import io
from pathlib import Path
from urllib.request import urlopen

SOURCE = 'https://www.fuzzwork.co.uk/dump/3670638_20261104_133007/csv/'
ROOT = Path(__file__).resolve().parents[1]

def table(name):
    with urlopen(SOURCE + name + '.csv', timeout=90) as response:
        content = response.read()
    print(name, 'sha256:', hashlib.sha256(content).hexdigest())
    return list(csv.DictReader(io.StringIO(content.decode('utf-8-sig'))))

def sql_string(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "''") + "'"

def generate(types, schematics, mapping):
    types = [t for t in types if t['marketGroupID'] in {'1333','1334','1335','1336','1337'}]
    ids = {t['typeID'] for t in types}
    assert len(ids) == 83, 'Unexpected PI item count; review source before updating seed'
    volumes = {'1333':.005, '1334':.19, '1335':.75, '1336':3., '1337':50.}
    assert all(float(t['volume']) == volumes[t['marketGroupID']] for t in types)
    assert all(m['typeID'] in ids for m in mapping)
    assert len(schematics) == 68, 'Unexpected schematic count'
    lines = ['-- PI subset of CCP EVE Online SDE, converted by Fuzzwork.', '-- Source: ' + SOURCE,
        '-- Generated by scripts/generate-pi-seed.py; regenerate rather than hand edit.',
        'CREATE TABLE invTypes (typeID INT PRIMARY KEY, typeName VARCHAR(255), marketGroupID INT, volume DOUBLE);',
        'CREATE TABLE planetSchematics (schematicID INT PRIMARY KEY, cycleTime INT);',
        'CREATE TABLE planetSchematicsTypeMap (schematicID INT, typeID INT, quantity INT, isInput BOOLEAN, PRIMARY KEY(schematicID,typeID));']
    for t in sorted(types, key=lambda t:int(t['typeID'])):
        lines.append('INSERT INTO invTypes VALUES (%s,%s,%s,%s);' % (t['typeID'],sql_string(t['typeName']),t['marketGroupID'],t['volume']))
    for s in schematics:
        lines.append('INSERT INTO planetSchematics VALUES (%s,%s);' % (s['schematicID'],s['cycleTime']))
    for m in mapping:
        lines.append('INSERT INTO planetSchematicsTypeMap VALUES (%s,%s,%s,%s);' % tuple(m[k] for k in ['schematicID','typeID','quantity','isInput']))
    out = ROOT / 'sql/local-init'; out.mkdir(parents=True, exist_ok=True)
    (out/'01-pi-data.sql').write_text('\n'.join(lines)+'\n')
    for source, dest in [('planetaryResourceTypeMap_rabbit.sql','02-planets.sql'),('planetSetupStorage_rabbit.sql','03-setups.sql')]:
        text=(ROOT/'sql'/source).read_text()
        text='\n'.join(l for l in text.splitlines() if not l.startswith('DROP TABLE') and not l.startswith('LOCK TABLES') and not l.startswith('UNLOCK TABLES'))
        (out/dest).write_text(text+'\n')
    (ROOT/'priceutils/src/main/resources/pi-type-ids.txt').write_text(','.join(sorted(ids,key=int))+'\n')
    print('Seed generated: %d items, %d schematics, %d recipe rows' % (len(types),len(schematics),len(mapping)))

if __name__ == '__main__':
    generate(table('invTypes'),table('planetSchematics'),table('planetSchematicsTypeMap'))
